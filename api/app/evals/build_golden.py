"""Build the golden retrieval set.

Labelling rule, stated plainly because it defines what the numbers mean:

    A chunk is *relevant* to a question if it contains the correct option's
    text (accent-insensitive, case-insensitive) and the question's stem shares
    vocabulary with it.

This is containment ground truth, not human judgement. It is objective and
reproducible, and it can only be built where the manual states the answer
verbatim — so true/false questions (whose options are "Verdadero"/"Falso") are
excluded. The output is committed and reviewed; re-running this script must not
silently change the benchmark, so the committed YAML is the source of truth.
"""

from __future__ import annotations

import asyncio
import json
from dataclasses import dataclass
from pathlib import Path

from sqlalchemy import select

from app.db import SessionLocal, dispose
from app.models import Chunk, Question
from app.rag.search import fold, tokens


@dataclass
class Candidate:
    question_id: str
    task: int
    chunk_id: str
    page: int
    section: str
    stem: str
    answer_text: str


def _clean(text: str) -> str:
    return fold(text).strip().strip(".").strip()


async def build(min_score: float = 0.15, per_task: int = 10) -> list[Candidate]:
    out: list[Candidate] = []
    async with SessionLocal() as session:
        chunks = list((await session.execute(select(Chunk).order_by(Chunk.id))).scalars())
        folded = {chunk.id: fold(chunk.body) for chunk in chunks}
        questions = list((await session.execute(select(Question).order_by(Question.id))).scalars())

        for question in questions:
            if question.kind != "mc":
                continue
            answer_text = next(
                (option["text"] for option in question.options if option["key"] == question.answer),
                "",
            )
            needle = _clean(answer_text)
            if len(needle) < 4:
                continue
            stem_terms = tokens(question.stem)
            best: tuple[float, Chunk] | None = None
            for chunk in chunks:
                if chunk.task != question.task:
                    continue
                body = folded[chunk.id]
                if needle not in body:
                    continue
                overlap = len(stem_terms & tokens(chunk.body)) / (len(stem_terms) or 1)
                if best is None or overlap > best[0]:
                    best = (overlap, chunk)
            if best is None or best[0] < min_score:
                continue
            overlap, chunk = best
            out.append(
                Candidate(
                    question_id=question.id,
                    task=question.task,
                    chunk_id=chunk.id,
                    page=chunk.page_from,
                    section=" > ".join(chunk.section_path),
                    stem=question.stem,
                    answer_text=answer_text,
                )
            )

    # Cap per task so one long section cannot dominate the metric.
    counts: dict[int, int] = {}
    capped: list[Candidate] = []
    for candidate in out:
        if counts.get(candidate.task, 0) >= per_task:
            continue
        counts[candidate.task] = counts.get(candidate.task, 0) + 1
        capped.append(candidate)
    return capped


def to_yaml(candidates: list[Candidate]) -> str:
    lines = [
        "# Golden retrieval set — generated by `python -m app.evals.build_golden`.",
        "#",
        "# Label rule: the chunk contains the correct option verbatim and shares",
        "# vocabulary with the stem. True/false items are excluded by construction.",
        "# Treat this file as the benchmark: regenerate only deliberately.",
        "#",
        f"# items: {len(candidates)}",
        "items:",
    ]
    for candidate in candidates:
        stem = candidate.stem.replace('"', "'")
        answer = candidate.answer_text.replace('"', "'")
        lines += [
            f'  - question_id: "{candidate.question_id}"',
            f"    task: {candidate.task}",
            f'    chunk_id: "{candidate.chunk_id}"',
            f"    page: {candidate.page}",
            f'    section: "{candidate.section}"',
            f'    stem: "{stem}"',
            f'    answer: "{answer}"',
        ]
    return "\n".join(lines) + "\n"


async def _run() -> None:
    try:
        candidates = await build()
        target = Path(__file__).with_name("golden.yaml")
        target.write_text(to_yaml(candidates), encoding="utf-8")
        per_task: dict[int, int] = {}
        for candidate in candidates:
            per_task[candidate.task] = per_task.get(candidate.task, 0) + 1
        print(json.dumps({"items": len(candidates), "per_task": per_task}, indent=2))
    finally:
        await dispose()


if __name__ == "__main__":
    asyncio.run(_run())
