"""ORM tables.

Enumerations are plain strings with CHECK constraints: migrations stay boring
and there is no Postgres ENUM to alter later.
"""

from __future__ import annotations

import uuid
from datetime import date, datetime
from decimal import Decimal
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Computed,
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    SmallInteger,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, TSVECTOR, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base


def _uuid() -> uuid.UUID:
    return uuid.uuid4()


class Document(Base):
    __tablename__ = "documents"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=_uuid)
    source_year: Mapped[int] = mapped_column(SmallInteger)
    filename: Mapped[str] = mapped_column(Text)
    sha256: Mapped[str] = mapped_column(Text, unique=True)
    pages: Mapped[int] = mapped_column(SmallInteger)
    ingested_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    chunks: Mapped[list[Chunk]] = relationship(back_populates="document", cascade="all, delete")


class Chunk(Base):
    __tablename__ = "chunks"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    document_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("documents.id", ondelete="CASCADE"), index=True
    )
    task: Mapped[int] = mapped_column(SmallInteger, index=True)
    section_path: Mapped[list[str]] = mapped_column(ARRAY(Text))
    page_from: Mapped[int] = mapped_column(SmallInteger)
    page_to: Mapped[int] = mapped_column(SmallInteger)
    body: Mapped[str] = mapped_column(Text)
    token_count: Mapped[int] = mapped_column(SmallInteger)
    # Generated by Postgres: no trigger, no application bookkeeping.
    tsv: Mapped[str | None] = mapped_column(
        TSVECTOR, Computed("to_tsvector('spanish', body)", persisted=True), nullable=True
    )

    document: Mapped[Document] = relationship(back_populates="chunks")
    embeddings: Mapped[list[ChunkEmbedding]] = relationship(
        back_populates="chunk", cascade="all, delete"
    )

    __table_args__ = (
        CheckConstraint("task BETWEEN 1 AND 5", name="task_range"),
        Index("ix_chunks_tsv", "tsv", postgresql_using="gin"),
    )


class ChunkEmbedding(Base):
    __tablename__ = "chunk_embeddings"

    chunk_id: Mapped[str] = mapped_column(
        Text, ForeignKey("chunks.id", ondelete="CASCADE"), primary_key=True
    )
    model: Mapped[str] = mapped_column(Text, primary_key=True)
    dim: Mapped[int] = mapped_column(SmallInteger)
    embedding: Mapped[list[float]] = mapped_column(Vector())

    chunk: Mapped[Chunk] = relationship(back_populates="embeddings")


class Question(Base):
    __tablename__ = "questions"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    task: Mapped[int] = mapped_column(SmallInteger, index=True)
    kind: Mapped[str] = mapped_column(Text)
    stem: Mapped[str] = mapped_column(Text)
    options: Mapped[list[dict[str, Any]]] = mapped_column(JSONB)
    answer: Mapped[str] = mapped_column(String(1))
    source_page: Mapped[int] = mapped_column(SmallInteger)
    source_year: Mapped[int] = mapped_column(SmallInteger)
    notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    __table_args__ = (
        CheckConstraint("task BETWEEN 1 AND 5", name="task_range"),
        CheckConstraint("kind IN ('mc','vf')", name="kind_valid"),
    )


class AnonUser(Base):
    __tablename__ = "anon_users"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=_uuid)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    last_seen_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )


class ExamSession(Base):
    __tablename__ = "exam_sessions"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=_uuid)
    anon_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("anon_users.id", ondelete="CASCADE"), index=True
    )
    mode: Mapped[str] = mapped_column(Text)
    # "end": correct everything on submit. "immediate": per-question verdict.
    feedback: Mapped[str] = mapped_column(Text, server_default="end")
    campaign_slot: Mapped[int | None] = mapped_column(SmallInteger, nullable=True)
    question_ids: Mapped[list[str]] = mapped_column(ARRAY(Text))
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    submitted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    score: Mapped[int | None] = mapped_column(SmallInteger, nullable=True)
    task_breakdown: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)
    duration_s: Mapped[int | None] = mapped_column(Integer, nullable=True)

    answers: Mapped[list[ExamAnswer]] = relationship(
        back_populates="session", cascade="all, delete"
    )

    __table_args__ = (
        CheckConstraint("mode IN ('campaign','random','practice')", name="mode_valid"),
        CheckConstraint("feedback IN ('end','immediate')", name="feedback_valid"),
        UniqueConstraint("anon_id", "mode", "campaign_slot", name="uq_campaign_slot"),
    )


class ExamAnswer(Base):
    __tablename__ = "exam_answers"

    exam_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("exam_sessions.id", ondelete="CASCADE"), primary_key=True
    )
    question_id: Mapped[str] = mapped_column(
        Text, ForeignKey("questions.id", ondelete="CASCADE"), primary_key=True, index=True
    )
    selected: Mapped[str | None] = mapped_column(String(1), nullable=True)
    is_correct: Mapped[bool] = mapped_column(Boolean)

    session: Mapped[ExamSession] = relationship(back_populates="answers")


class Explanation(Base):
    __tablename__ = "explanations"

    question_id: Mapped[str] = mapped_column(
        Text, ForeignKey("questions.id", ondelete="CASCADE"), primary_key=True
    )
    model: Mapped[str] = mapped_column(Text, primary_key=True)
    prompt_version: Mapped[str] = mapped_column(Text, primary_key=True)
    retrieval_cfg: Mapped[str] = mapped_column(Text, primary_key=True)
    model_id: Mapped[str] = mapped_column(Text)
    body_es: Mapped[str] = mapped_column(Text)
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default="{}")
    citations: Mapped[list[dict[str, Any]]] = mapped_column(JSONB)
    confidence: Mapped[Decimal | None] = mapped_column(Numeric(3, 2), nullable=True)
    status: Mapped[str] = mapped_column(Text, server_default="draft")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    __table_args__ = (
        CheckConstraint("status IN ('draft','reviewed','rejected')", name="status_valid"),
    )


class EvalRun(Base):
    __tablename__ = "eval_runs"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=_uuid)
    git_sha: Mapped[str] = mapped_column(Text)
    config: Mapped[str] = mapped_column(Text)
    models: Mapped[list[str]] = mapped_column(ARRAY(Text))
    metrics: Mapped[dict[str, Any]] = mapped_column(JSONB)
    cost_eur: Mapped[Decimal | None] = mapped_column(Numeric(8, 4), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class LlmUsage(Base):
    __tablename__ = "llm_usage"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    kind: Mapped[str] = mapped_column(Text)
    provider: Mapped[str] = mapped_column(Text)
    model_id: Mapped[str] = mapped_column(Text)
    tokens_in: Mapped[int] = mapped_column(Integer)
    tokens_out: Mapped[int] = mapped_column(Integer)
    cost_eur: Mapped[Decimal] = mapped_column(Numeric(8, 4))
    latency_ms: Mapped[int] = mapped_column(Integer)
    fell_back: Mapped[bool] = mapped_column(Boolean, server_default="false")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class Quota(Base):
    __tablename__ = "quota"

    anon_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("anon_users.id", ondelete="CASCADE"), primary_key=True
    )
    day: Mapped[date] = mapped_column(Date, primary_key=True)
    tutor_requests: Mapped[int] = mapped_column(SmallInteger, server_default="0")
    tokens_used: Mapped[int] = mapped_column(Integer, server_default="0")


