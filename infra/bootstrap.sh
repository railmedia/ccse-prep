#!/usr/bin/env bash
#
# Load the production data: manual -> questions/chunks -> embeddings ->
# explanations. Run on the server, from the directory that holds .env and
# infra/ (the same place deploy.sh runs from).
#
#   ./infra/bootstrap.sh                 # first run
#   ./infra/bootstrap.sh --force         # re-ingest a changed manual
#   ./infra/bootstrap.sh --explanations  # only regenerate explanations
#
# Safe to re-run: ingestion is guarded by the PDF's SHA-256, embeddings skip
# finished models, and explanations are upserts.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

ENVFILE="${ENVFILE:-.env}"
if [[ ! -f "$ENVFILE" ]]; then
  echo "missing $ENVFILE — copy env.prod.example and fill it in" >&2
  exit 1
fi

if docker compose version >/dev/null 2>&1; then
  COMPOSE=(docker compose)
else
  COMPOSE=(docker-compose)
fi

read_env() {
  grep -E "^$1=" "$ENVFILE" | tail -1 | cut -d= -f2- || true
}

MANUAL_URL="$(read_env MANUAL_URL)"
MANUAL_YEAR="$(read_env MANUAL_YEAR)"
MANUAL_YEAR="${MANUAL_YEAR:-2026}"
POSTGRES_USER="$(read_env POSTGRES_USER)"
POSTGRES_USER="${POSTGRES_USER:-ccse}"
POSTGRES_DB="$(read_env POSTGRES_DB)"
POSTGRES_DB="${POSTGRES_DB:-ccse}"

FORCE=0
EXPLANATIONS_ONLY=0
for arg in "$@"; do
  case "$arg" in
    --force) FORCE=1 ;;
    --explanations) EXPLANATIONS_ONLY=1 ;;
    -h|--help)
      sed -n '2,16p' "$0"
      exit 0
      ;;
    *)
      echo "unknown argument: $arg" >&2
      exit 2
      ;;
  esac
done

run_compose() {
  "${COMPOSE[@]}" -f infra/compose.yml -f infra/compose.prod.yml --env-file "$ENVFILE" "$@"
}

echo "==> checking the stack"
run_compose ps postgres >/dev/null

if [[ "$EXPLANATIONS_ONLY" -eq 0 ]]; then
  if [[ -z "$MANUAL_URL" ]]; then
    echo "MANUAL_URL is not set in $ENVFILE" >&2
    exit 1
  fi

  PDF="data/manual/manual-ccse-${MANUAL_YEAR}.pdf"
  mkdir -p "$(dirname "$PDF")"
  if [[ -f "$PDF" && "$FORCE" -eq 0 ]]; then
    echo "==> using existing $PDF"
  else
    echo "==> downloading the manual"
    curl -fSL --retry 3 --retry-delay 2 -o "${PDF}.part" "$MANUAL_URL"
    mv "${PDF}.part" "$PDF"
  fi

  echo "==> ingesting ($PDF)"
  INGEST_ARGS=()
  [[ "$FORCE" -eq 1 ]] && INGEST_ARGS+=(--force)
  run_compose run --rm -v "$ROOT/data:/data:ro" api \
    python -m app.jobs.ingest "/data/manual/$(basename "$PDF")" "${INGEST_ARGS[@]}"

  echo "==> embedding chunks"
  EMBED_ARGS=()
  [[ "$FORCE" -eq 1 ]] && EMBED_ARGS+=(--force)
  run_compose run --rm api python -m app.jobs.embed "${EMBED_ARGS[@]}"
fi

echo "==> generating explanations"
run_compose run --rm api python -m app.jobs.precompute

echo "==> counts"
run_compose exec -T postgres psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -tAc \
  "select 'questions='||count(*) from questions
   union all select 'chunks='||count(*) from chunks
   union all select 'embeddings='||count(*) from chunk_embeddings
   union all select 'explanations='||count(*) from explanations"

if [[ -z "$(read_env MISTRAL_API_KEY)$(read_env OPENAI_API_KEY)" ]]; then
  echo "note: no LLM API key set — explanations were generated by the"
  echo "      deterministic extractive fallback. Add a key and re-run"
  echo "      with --explanations to regenerate them with a model."
fi

echo "==> done"
